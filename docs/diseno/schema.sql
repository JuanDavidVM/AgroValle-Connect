-- Fuente de verdad: el Diagrama Entidad-Relación (docs/diseno/modelo-datos-der.png), con tres
-- ajustes que el código necesita y que deben reflejarse también en el diagrama:
--   1. usuario.rol                : rol del usuario (AGRICULTOR o COMPRADOR); lo usa el JWT.
--   2. fincas.fecha_registro      : marca de tiempo del registro de la finca.
--   3. registros_auditoria        : trazabilidad de acciones (suscriptor del patron Observer).
--
-- Las tablas de las historias aun no implementadas (carritos, reservas, ordenes, detalles_orden,
-- despachos, seguimiento_despachos y mensajes) quedan definidas para completar el modelo.
--
-- USO: solo en una base de DESARROLLO. El script borra y recrea las tablas.
--   Supabase > SQL Editor > pegar y ejecutar. Despues arrancar la aplicacion; el arranque
--   tambien siembra los catalogos de forma idempotente.
-- =============================================================================================

BEGIN;

DROP TABLE IF EXISTS seguimiento_despachos, despachos, mensajes, detalles_orden, reservas, carritos,
    ordenes, registros_auditoria, productos, fincas, compradores_comerciales, agricultores,
    usuario, categorias, municipios CASCADE;

-- ---------------------------------------------------------------------------------------------
-- Catalogos
-- ---------------------------------------------------------------------------------------------
CREATE TABLE municipios (
    id_municipio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(80) NOT NULL,
    CONSTRAINT uk_municipios_nombre UNIQUE (nombre)
);

CREATE TABLE categorias (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(40) NOT NULL,
    CONSTRAINT uk_categorias_nombre UNIQUE (nombre)
);

-- ---------------------------------------------------------------------------------------------
-- Usuarios y perfiles
-- ---------------------------------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo         VARCHAR(150) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    rol            VARCHAR(20)  NOT NULL,
    fecha_creacion TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('AGRICULTOR', 'COMPRADOR'))
);

CREATE TABLE agricultores (
    id_agricultor   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(120) NOT NULL,
    documento       VARCHAR(12)  NOT NULL,
    telefono        VARCHAR(20)  NOT NULL,
    fecha_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_municipio    BIGINT       NOT NULL,
    id_usuario      BIGINT       NOT NULL,
    CONSTRAINT uk_agricultores_documento UNIQUE (documento),
    CONSTRAINT uk_agricultores_usuario UNIQUE (id_usuario),
    CONSTRAINT fk_agricultores_municipio FOREIGN KEY (id_municipio) REFERENCES municipios (id_municipio),
    CONSTRAINT fk_agricultores_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

CREATE TABLE compradores_comerciales (
    id_comprador        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social        VARCHAR(150) NOT NULL,
    nit                 VARCHAR(13)  NOT NULL,
    telefono            VARCHAR(20)  NOT NULL,
    direccion_comercial VARCHAR(200) NOT NULL,
    fecha_registro      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_municipio        BIGINT       NOT NULL,
    id_usuario          BIGINT       NOT NULL,
    CONSTRAINT uk_compradores_nit UNIQUE (nit),
    CONSTRAINT uk_compradores_usuario UNIQUE (id_usuario),
    CONSTRAINT fk_compradores_municipio FOREIGN KEY (id_municipio) REFERENCES municipios (id_municipio),
    CONSTRAINT fk_compradores_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

-- ---------------------------------------------------------------------------------------------
-- Oferta agricola
-- ---------------------------------------------------------------------------------------------
CREATE TABLE fincas (
    id_finca       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_finca   VARCHAR(100)  NOT NULL,
    hectareas      NUMERIC(8, 2) NOT NULL,
    fecha_registro TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_agricultor  BIGINT        NOT NULL,
    id_municipio   BIGINT        NOT NULL,
    CONSTRAINT uk_fincas_agricultor_nombre UNIQUE (id_agricultor, nombre_finca),
    CONSTRAINT ck_fincas_hectareas CHECK (hectareas > 0),
    CONSTRAINT fk_fincas_agricultor FOREIGN KEY (id_agricultor) REFERENCES agricultores (id_agricultor),
    CONSTRAINT fk_fincas_municipio FOREIGN KEY (id_municipio) REFERENCES municipios (id_municipio)
);

CREATE TABLE productos (
    id_producto          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre               VARCHAR(80)    NOT NULL,
    descripcion          VARCHAR(255),
    unidad_medida        VARCHAR(20)    NOT NULL DEFAULT 'kg',
    cantidad_disponible  NUMERIC(10, 2) NOT NULL,
    precio_unitario      NUMERIC(12, 2) NOT NULL,
    fecha_cosecha        DATE           NOT NULL,
    estado               VARCHAR(20)    NOT NULL,
    version              BIGINT         NOT NULL DEFAULT 0,
    fecha_publicacion    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_categoria         BIGINT         NOT NULL,
    id_finca             BIGINT         NOT NULL,
    CONSTRAINT ck_productos_cantidad CHECK (cantidad_disponible >= 0),
    CONSTRAINT ck_productos_precio CHECK (precio_unitario > 0),
    CONSTRAINT ck_productos_estado CHECK (estado IN ('ACTIVA', 'INACTIVA')),
    CONSTRAINT fk_productos_categoria FOREIGN KEY (id_categoria) REFERENCES categorias (id_categoria),
    CONSTRAINT fk_productos_finca FOREIGN KEY (id_finca) REFERENCES fincas (id_finca)
);

-- ---------------------------------------------------------------------------------------------
-- Auditoria (suscriptor del evento CosechaPublicadaEvent)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE registros_auditoria (
    id_registro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion      VARCHAR(60)  NOT NULL,
    entidad     VARCHAR(60)  NOT NULL,
    entidad_id  BIGINT,
    usuario     VARCHAR(150) NOT NULL,
    detalle     VARCHAR(500),
    fecha       TIMESTAMP    NOT NULL
);

-- ---------------------------------------------------------------------------------------------
-- Compras (historias HU-05, HU-10 a HU-13): definidas, aun sin entidades JPA
-- ---------------------------------------------------------------------------------------------
CREATE TABLE ordenes (
    id_orden           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_orden       VARCHAR(30) NOT NULL,
    estado             VARCHAR(20) NOT NULL,
    fecha_creacion     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_alistamiento TIMESTAMP,
    id_comprador       BIGINT      NOT NULL,
    id_agricultor      BIGINT      NOT NULL,
    CONSTRAINT uk_ordenes_numero UNIQUE (numero_orden),
    CONSTRAINT fk_ordenes_comprador FOREIGN KEY (id_comprador) REFERENCES compradores_comerciales (id_comprador),
    CONSTRAINT fk_ordenes_agricultor FOREIGN KEY (id_agricultor) REFERENCES agricultores (id_agricultor)
);

CREATE TABLE carritos (
    id_carrito     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad       NUMERIC(10, 2) NOT NULL,
    fecha_creacion TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_comprador   BIGINT         NOT NULL,
    id_producto    BIGINT         NOT NULL,
    CONSTRAINT ck_carritos_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_carritos_comprador FOREIGN KEY (id_comprador) REFERENCES compradores_comerciales (id_comprador),
    CONSTRAINT fk_carritos_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto)
);

CREATE TABLE reservas (
    id_reserva    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad      NUMERIC(10, 2) NOT NULL,
    estado        VARCHAR(20)    NOT NULL,
    fecha_reserva TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_comprador  BIGINT         NOT NULL,
    id_producto   BIGINT         NOT NULL,
    id_orden      BIGINT,
    CONSTRAINT ck_reservas_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_reservas_comprador FOREIGN KEY (id_comprador) REFERENCES compradores_comerciales (id_comprador),
    CONSTRAINT fk_reservas_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto),
    CONSTRAINT fk_reservas_orden FOREIGN KEY (id_orden) REFERENCES ordenes (id_orden)
);

CREATE TABLE detalles_orden (
    id_detalle_orden BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad         NUMERIC(10, 2) NOT NULL,
    precio_unitario  NUMERIC(12, 2) NOT NULL,
    id_orden         BIGINT         NOT NULL,
    id_producto      BIGINT         NOT NULL,
    CONSTRAINT ck_detalles_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalles_precio CHECK (precio_unitario > 0),
    CONSTRAINT fk_detalles_orden FOREIGN KEY (id_orden) REFERENCES ordenes (id_orden),
    CONSTRAINT fk_detalles_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto)
);

-- ---------------------------------------------------------------------------------------------
-- Logistica y mensajeria (historias HU-05, HU-14 y HU-15)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE despachos (
    id_despacho         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_despacho      DATE         NOT NULL,
    direccion_destino   VARCHAR(200) NOT NULL,
    estado              VARCHAR(20)  NOT NULL,
    id_orden            BIGINT       NOT NULL,
    id_municipio_origen BIGINT       NOT NULL,
    CONSTRAINT fk_despachos_orden FOREIGN KEY (id_orden) REFERENCES ordenes (id_orden),
    CONSTRAINT fk_despachos_municipio FOREIGN KEY (id_municipio_origen) REFERENCES municipios (id_municipio)
);

CREATE TABLE seguimiento_despachos (
    id_seguimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado         VARCHAR(20) NOT NULL,
    fecha_hora     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion    VARCHAR(255),
    id_despacho    BIGINT      NOT NULL,
    CONSTRAINT fk_seguimiento_despacho FOREIGN KEY (id_despacho) REFERENCES despachos (id_despacho)
);

CREATE TABLE mensajes (
    id_mensaje        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido         VARCHAR(1000) NOT NULL,
    fecha_envio       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_orden          BIGINT        NOT NULL,
    id_usuario_emisor BIGINT        NOT NULL,
    CONSTRAINT fk_mensajes_orden FOREIGN KEY (id_orden) REFERENCES ordenes (id_orden),
    CONSTRAINT fk_mensajes_emisor FOREIGN KEY (id_usuario_emisor) REFERENCES usuario (id_usuario)
);

-- ---------------------------------------------------------------------------------------------
-- Indices para las consultas del filtro de ofertas (HU-04) y para las llaves foraneas
-- ---------------------------------------------------------------------------------------------
CREATE INDEX idx_productos_estado_categoria ON productos (estado, id_categoria);
CREATE INDEX idx_productos_finca ON productos (id_finca);
CREATE INDEX idx_fincas_municipio ON fincas (id_municipio);
CREATE INDEX idx_agricultores_municipio ON agricultores (id_municipio);
CREATE INDEX idx_ordenes_comprador ON ordenes (id_comprador);
CREATE INDEX idx_ordenes_agricultor ON ordenes (id_agricultor);

