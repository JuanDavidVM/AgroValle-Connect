-- =============================================================================================
-- V2 - Tabla de mensajes sobre una oferta (habilita HU-05)
--
-- La tabla no existia en la base: nunca se creo porque no tenia entidad JPA y Hibernate solo crea
-- lo que las entidades declaran. Se crea aqui con la forma que HU-05 necesita, donde el mensaje
-- cuelga de una oferta o de una orden.
--
-- El CREATE va con IF NOT EXISTS y las alteraciones posteriores son idempotentes para cubrir el
-- caso de una base donde la tabla si exista con la forma vieja, por ejemplo si alguien ejecuto el
-- script de diseno completo.
-- =============================================================================================

CREATE TABLE IF NOT EXISTS mensajes (
    id_mensaje        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido         VARCHAR(1000) NOT NULL,
    fecha_envio       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_producto       BIGINT,
    id_orden          BIGINT,
    id_usuario_emisor BIGINT        NOT NULL,
    CONSTRAINT ck_mensajes_contexto CHECK (id_producto IS NOT NULL OR id_orden IS NOT NULL),
    CONSTRAINT fk_mensajes_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto),
    CONSTRAINT fk_mensajes_orden FOREIGN KEY (id_orden) REFERENCES ordenes (id_orden),
    CONSTRAINT fk_mensajes_emisor FOREIGN KEY (id_usuario_emisor) REFERENCES usuario (id_usuario)
);

ALTER TABLE mensajes ADD COLUMN IF NOT EXISTS id_producto BIGINT;

ALTER TABLE mensajes ALTER COLUMN id_orden DROP NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_mensajes_producto') THEN
        ALTER TABLE mensajes
            ADD CONSTRAINT fk_mensajes_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_mensajes_contexto') THEN
        ALTER TABLE mensajes
            ADD CONSTRAINT ck_mensajes_contexto CHECK (id_producto IS NOT NULL OR id_orden IS NOT NULL);
    END IF;
END $$;
